// Numéro de série Excel d'une date « AAAA-MM-JJ » (jours depuis le 30/12/1899).
export function excelDate(iso) {
  const [y, m, d] = String(iso).split('-').map(Number);
  if (!y || !m || !d) return null;
  return (Date.UTC(y, m - 1, d) - Date.UTC(1899, 11, 30)) / 86400000;
}

// Valeurs de cellule acceptées :
//   'texte' | 123 | { date: 'AAAA-MM-JJ' } | { formula: 'TODAY()-A2', style } | { link: url, text } | null
function cellXml(value, ref, colStyle) {
  if (value === null || value === undefined || value === '') return '';
  if (typeof value === 'number') return `<c r="${ref}" s="${colStyle ?? STYLE.default}"><v>${value}</v></c>`;
  if (typeof value === 'object') {
    if ('date' in value) {
      const serial = excelDate(value.date);
      return serial === null ? '' : `<c r="${ref}" s="${STYLE.date}"><v>${serial}</v></c>`;
    }
    if ('formula' in value) return `<c r="${ref}" s="${value.style ?? colStyle ?? STYLE.default}"><f>${xmlEscape(value.formula)}</f></c>`;
    if ('link' in value) {
      const url = String(value.link);
      // HYPERLINK() est limité à 255 caractères par argument : au-delà on garde l'URL en texte brut.
      if (url.length <= 250) {
        const q = (s) => `"${String(s).replace(/"/g, '""')}"`;
        return `<c r="${ref}" s="${STYLE.link}" t="str"><f>${xmlEscape(`HYPERLINK(${q(url)},${q(value.text || url)})`)}</f><v>${xmlEscape(value.text || url)}</v></c>`;
      }
      value = url;
    }
  }
  return `<c r="${ref}" s="${colStyle ?? STYLE.default}" t="inlineStr"><is><t xml:space="preserve">${xmlEscape(value)}</t></is></c>`;
}

/**
 * @param {{ sheetName: string, columns: {header: string, width?: number, style?: number}[], rows: any[][] }} sheet
 * @returns {Blob}
 */
export function buildXlsx({ sheetName, columns, rows }) {
  const name = xmlEscape(sheetName.replace(/[\\/?*[\]:]/g, ' ').slice(0, 31));
  const lastCol = colName(columns.length - 1);
  const lastRow = rows.length + 1;

  const cols = columns.map((c, i) => `<col min="${i + 1}" max="${i + 1}" width="${c.width || 15}" customWidth="1"/>`).join('');
  const header = `<row r="1" ht="22" customHeight="1">${columns.map((c, i) => cellXml(c.header, `${colName(i)}1`, STYLE.header)).join('')}</row>`;
  const body = rows
    .map((row, r) => `<row r="${r + 2}">${row.map((v, i) => cellXml(v, `${colName(i)}${r + 2}`, columns[i]?.style)).join('')}</row>`)
    .join('');

  const sheetXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheetViews><sheetView workbookViewId="0"><pane ySplit="1" topLeftCell="A2" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>
<sheetFormatPr defaultRowHeight="15"/>
<cols>${cols}</cols>
<sheetData>${header}${body}</sheetData>
<autoFilter ref="A1:${lastCol}${lastRow}"/>
</worksheet>`;

  const workbookXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">
<sheets><sheet name="${name}" sheetId="1" r:id="rId1"/></sheets>
<definedNames><definedName name="_xlnm._FilterDatabase" localSheetId="0" hidden="1">'${name.replace(/'/g, "''")}'!$A$1:$${lastCol}$${lastRow}</definedName></definedNames>
<calcPr calcId="191029" fullCalcOnLoad="1"/>
</workbook>`;

  return zip([
    {
      name: '[Content_Types].xml',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">
<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>
<Default Extension="xml" ContentType="application/xml"/>
<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>
<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>
<Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/>
</Types>`,
    },
    {
      name: '_rels/.rels',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>
</Relationships>`,
    },
    { name: 'xl/workbook.xml', data: workbookXml },
    {
      name: 'xl/_rels/workbook.xml.rels',
      data: `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">
<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>
<Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/>
</Relationships>`,
    },
    { name: 'xl/worksheets/sheet1.xml', data: sheetXml },
    { name: 'xl/styles.xml', data: STYLES_XML },
  ]);
}
